def group_ccfolia_skills(edition, skill_values):
    """Group saved skills without changing their names, values or relative order."""
    categories = CCFOLIA_SKILL_CATEGORIES[edition]
    category_by_skill = {skill: category for category, names in categories.items() for skill in names}
    grouped = {category: [] for category in (*categories, "その他・独自")}
    for name, value in skill_values.items():
        grouped[category_by_skill.get(name, "その他・独自")].append((name, value))
    return {category: entries for category, entries in grouped.items() if entries}
